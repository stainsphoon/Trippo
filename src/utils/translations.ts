export const translateText = (key: keyof typeof translations['ko'], lang: Language, params?: Record<string, string | number>): string => {
  const dict = translations[lang] || translations['ko'];
  let text = dict[key] || translations['ko'][key] || String(key);
  
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
};
